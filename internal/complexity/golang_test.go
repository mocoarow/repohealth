package complexity_test

import (
	"go/scanner"
	"io/fs"
	"strings"
	"testing"
	"testing/fstest"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/mocoarow/repohealth/internal/complexity"
	"github.com/mocoarow/repohealth/internal/config"
)

const nested = `package a

func Nested(xs []int) int {
	n := 0
	for _, x := range xs {
		if x > 0 {
			if x%2 == 0 {
				n++
			}
		}
	}
	return n
}
`

const methods = `package a

type T struct{}

func (t *T) Pointer() {}

func (t T) Value() {}

type L[E any] struct{}

func (l *L[E]) Generic() {}

type M[K comparable, V any] struct{}

func (m M[K, V]) Pair() {}
`

func testConfig() config.Config {
	return config.Config{
		Root:    "/repo",
		Version: 1,
		Areas:   []config.Area{{Name: "svc", Paths: []string{"svc"}}},
		Groups:  nil,
		Exclude: []string{"svc/gen/**"},
	}
}

func file(src string) *fstest.MapFile {
	return &fstest.MapFile{Data: []byte(src)}
}

func Test_Go_shouldReturnBothComplexities_whenFunctionIsNested(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{"svc/a.go": file(nested)}

	// when
	got, err := complexity.Go(fsys, testConfig(), []string{"svc/a.go"})

	// then
	require.NoError(t, err)
	assert.Equal(t, []complexity.Function{{File: "svc/a.go", Line: 3, Name: "Nested", Cyclo: 4, Cognit: 6}}, got)
}

func Test_Go_shouldNameMethodsWithReceiver_whenFunctionsAreMethods(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{"svc/m.go": file(methods)}

	// when
	got, err := complexity.Go(fsys, testConfig(), []string{"svc/m.go"})

	// then
	require.NoError(t, err)
	assert.Equal(t, []string{"(*T).Pointer", "(T).Value", "(*L).Generic", "(M).Pair"}, names(got))
}

func Test_Go_shouldMeasureFunction_whenItHasIgnoreDirectives(t *testing.T) {
	t.Parallel()

	// given
	src := "package a\n\n//gocyclo:ignore\n//gocognit:ignore\n" + strings.TrimPrefix(nested, "package a\n\n")
	fsys := fstest.MapFS{"svc/a.go": file(src)}

	// when
	got, err := complexity.Go(fsys, testConfig(), []string{"svc/a.go"})

	// then
	require.NoError(t, err)
	assert.Equal(t, []complexity.Function{{File: "svc/a.go", Line: 5, Name: "Nested", Cyclo: 4, Cognit: 6}}, got)
}

func Test_Go_shouldSkipFile_whenFileIsNotCounted(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		path string
		src  string
	}{
		{name: "test file", path: "svc/a_test.go", src: nested},
		{name: "generated file", path: "svc/a.pb.go", src: "// Code generated by protoc-gen-go. DO NOT EDIT.\n\n" + nested},
		{name: "excluded file", path: "svc/gen/a.go", src: nested},
		{name: "outside every area", path: "tools/a.go", src: nested},
		{name: "not go", path: "svc/a.ts", src: "not go"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			// given
			fsys := fstest.MapFS{tt.path: file(tt.src)}

			// when
			got, err := complexity.Go(fsys, testConfig(), []string{tt.path})

			// then
			require.NoError(t, err)
			assert.Empty(t, got)
		})
	}
}

func Test_Go_shouldSortByFileAndLine_whenFilesAreGivenOutOfOrder(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{"svc/b.go": file(nested), "svc/a.go": file(methods)}

	// when
	got, err := complexity.Go(fsys, testConfig(), []string{"svc/b.go", "svc/a.go"})

	// then
	require.NoError(t, err)
	assert.Equal(t, []string{"(*T).Pointer", "(T).Value", "(*L).Generic", "(M).Pair", "Nested"}, names(got))
}

func Test_Go_shouldReturnErrNotExist_whenFileIsMissing(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{}

	// when
	_, err := complexity.Go(fsys, testConfig(), []string{"svc/a.go"})

	// then
	require.ErrorIs(t, err, fs.ErrNotExist)
}

func Test_Go_shouldReturnError_whenFileDoesNotParse(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{"svc/a.go": file("package a\nfunc {")}

	// when
	_, err := complexity.Go(fsys, testConfig(), []string{"svc/a.go"})

	// then
	var parseErr scanner.ErrorList
	require.ErrorAs(t, err, &parseErr)
}

func names(funcs []complexity.Function) []string {
	out := make([]string, 0, len(funcs))
	for _, f := range funcs {
		out = append(out, f.Name)
	}

	return out
}
