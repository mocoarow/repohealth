package size_test

import (
	"go/scanner"
	"io/fs"
	"testing"
	"testing/fstest"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/mocoarow/repohealth/internal/config"
	"github.com/mocoarow/repohealth/internal/size"
	"github.com/mocoarow/repohealth/internal/source"
)

func file(src string) *fstest.MapFile {
	return &fstest.MapFile{Data: []byte(src)}
}

func testConfig() config.Config {
	return config.Config{
		Root:    "/repo",
		Version: 1,
		Areas: []config.Area{
			{Name: "auth", Paths: []string{"svc-auth"}},
			{Name: "web", Paths: []string{"web"}},
		},
		Groups:         nil,
		Exclude:        nil,
		StablePackages: nil,
		Coverage:       nil,
	}
}

func Test_Measure_shouldCountLinesPerFile_whenFilesAreSources(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{
		"svc-auth/user.go":      file("package auth\n\nfunc a() {}\n"),
		"svc-auth/user_test.go": file("package auth_test\n"),
		"web/app.tsx":           file("export const a = 1;\nexport const b = 2;\n"),
		"web/app.test.tsx":      file("test()\n"),
	}
	files := []string{"svc-auth/user.go", "svc-auth/user_test.go", "web/app.tsx", "web/app.test.tsx"}

	// when
	got, err := size.Measure(fsys, testConfig(), files)

	// then
	require.NoError(t, err)
	assert.Equal(t, []size.File{
		{Path: "svc-auth/user.go", Area: "auth", Lang: source.Go, Test: false, Lines: 3},
		{Path: "svc-auth/user_test.go", Area: "auth", Lang: source.Go, Test: true, Lines: 1},
		{Path: "web/app.tsx", Area: "web", Lang: source.Script, Test: false, Lines: 2},
		{Path: "web/app.test.tsx", Area: "web", Lang: source.Script, Test: true, Lines: 1},
	}, got)
}

func Test_Measure_shouldNotCountLastLine_whenFileLacksFinalNewline(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{"web/app.ts": file("a;\nb;")}

	// when
	got, err := size.Measure(fsys, testConfig(), []string{"web/app.ts"})

	// then
	require.NoError(t, err)
	require.Len(t, got, 1)
	assert.Equal(t, 1, got[0].Lines)
}

func Test_Measure_shouldSkipFile_whenFileIsNotMeasured(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		path string
		src  string
	}{
		{name: "generated go", path: "svc-auth/api.pb.go", src: "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage auth\n"},
		{name: "generated go test", path: "svc-auth/mock_test.go", src: "// Code generated by mockery. DO NOT EDIT.\n\npackage auth_test\n"},
		{name: "other extension", path: "svc-auth/README.md", src: "# auth\n"},
		{name: "outside every area", path: "tools/t.go", src: "package tools\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			// given
			fsys := fstest.MapFS{tt.path: file(tt.src)}

			// when
			got, err := size.Measure(fsys, testConfig(), []string{tt.path})

			// then
			require.NoError(t, err)
			assert.Empty(t, got)
		})
	}
}

func Test_Measure_shouldReturnErrNotExist_whenFileIsMissing(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{}

	// when
	_, err := size.Measure(fsys, testConfig(), []string{"svc-auth/user.go"})

	// then
	require.ErrorIs(t, err, fs.ErrNotExist)
}

func Test_Measure_shouldReturnScannerError_whenGoFileHasNoPackageClause(t *testing.T) {
	t.Parallel()

	// given
	fsys := fstest.MapFS{"svc-auth/user.go": file("func a() {}\n")}

	// when
	_, err := size.Measure(fsys, testConfig(), []string{"svc-auth/user.go"})

	// then
	var parseErr scanner.ErrorList
	require.ErrorAs(t, err, &parseErr)
}
